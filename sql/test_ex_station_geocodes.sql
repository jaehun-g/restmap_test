  `geocode_error_code` VARCHAR(80) NULL,
  `source_fetched_at` DATETIME(3) NOT NULL,
  `geocoded_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_test_ex_station_geocodes_source_key` (`source_key`),
  KEY `ix_test_ex_station_geocodes_service_area_code` (`service_area_code`),
  KEY `ix_test_ex_station_geocodes_coordinates` (`latitude`, `longitude`)
