  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `source_key` VARCHAR(255) NOT NULL,
  `route_code` VARCHAR(50) NULL,
  `service_area_code` VARCHAR(50) NOT NULL,
  `route_name` VARCHAR(120) NULL,
  `direction` VARCHAR(50) NULL,
  `service_area_name` VARCHAR(150) NULL,
  `oil_company` VARCHAR(80) NULL,
  `source_location` VARCHAR(255) NULL,
  `tel_no` VARCHAR(30) NULL,
  `lpg_available` TINYINT(1) NULL,
  `gasoline_price` DECIMAL(10, 1) NULL,
  `diesel_price` DECIMAL(10, 1) NULL,
  `lpg_price` DECIMAL(10, 1) NULL,
  `latitude` DECIMAL(10, 7) NULL,
  `longitude` DECIMAL(11, 7) NULL,
  `kakao_address_name` VARCHAR(255) NULL,
  `kakao_address_type` VARCHAR(20) NULL,
  `kakao_parcel_address_name` VARCHAR(255) NULL,
  `kakao_road_address_name` VARCHAR(255) NULL,
